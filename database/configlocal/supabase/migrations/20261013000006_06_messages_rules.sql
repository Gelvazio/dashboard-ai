-- Dashboard AI — 06_messages_rules.sql  (SUB-31)
-- Recados entre agentes e regras por projeto, genéricos para qualquer projeto.
--
--   agent_messages : recados entre agentes/frentes (e pessoas), por projeto e,
--                    opcionalmente, por task. destinatario nulo = todos.
--   project_rules  : cópia, por seção, das regras do repositório de cada projeto
--                    (AGENTS.md, CLAUDE.md, ...), com md5 para conferir se o banco
--                    está igual ao arquivo (conferir_regras).
--
-- Acesso (RLS):
--   * agent_messages: viewer lê; editor cria e marca como lido/arquivado (só as
--     colunas lido_em, lido_por e arquivado); sem DELETE pela interface.
--   * project_rules : viewer lê; só owner do projeto (ou administrador) escreve —
--     regras viram instrução para os agentes, então a escrita é restrita.
--   * service_role (MCP, scripts) ignora RLS; anon não tem acesso.
--
-- Idempotente. Depende de 00 a 05 (aplicar depois do 05).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- agent_messages
-- -----------------------------------------------------------------------------
create table if not exists public.agent_messages (
    id           bigint      generated by default as identity primary key,
    project_id   bigint      not null references public.projects (id) on delete cascade,
    task_id      bigint      references public.tasks (id) on delete set null,
    task_codigo  text,                                     -- preenchido pelo trigger
    remetente    text        not null,                     -- agente/frente/pessoa que escreveu
    destinatario text,                                     -- null = todos do projeto
    tipo         text        not null default 'recado',
    assunto      text,
    mensagem     text        not null,
    resposta_de  bigint      references public.agent_messages (id) on delete set null,
    lido_em      timestamptz,
    lido_por     text,
    arquivado    boolean     not null default false,
    metadados    jsonb       not null default '{}'::jsonb,
    criado_por   uuid        default public.usuario_atual(),
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    constraint agent_messages_tipo_check
      check (tipo in ('recado', 'pergunta', 'resposta', 'alerta', 'handoff')),
    constraint agent_messages_remetente_check check (btrim(remetente) <> '' and length(remetente) <= 120),
    constraint agent_messages_destinatario_check check (destinatario is null or (btrim(destinatario) <> '' and length(destinatario) <= 120)),
    constraint agent_messages_mensagem_check check (btrim(mensagem) <> '' and length(mensagem) <= 50000),
    constraint agent_messages_metadados_check check (jsonb_typeof(metadados) = 'object')
);

comment on table public.agent_messages is
  'Recados entre agentes/frentes de um projeto (opcionalmente ligados a uma task). destinatario nulo = todos.';

create index if not exists agent_messages_caixa_idx
    on public.agent_messages (project_id, destinatario, created_at desc) where not arquivado;
create index if not exists agent_messages_task_idx on public.agent_messages (task_id) where task_id is not null;
create index if not exists agent_messages_resposta_idx on public.agent_messages (resposta_de) where resposta_de is not null;

-- Validação: task e recado respondido do mesmo projeto; campos imutáveis.
-- security invoker de propósito: current_user identifica a interface e a busca da
-- task respeita a RLS (a interface não enxerga tasks de outros projetos).
create or replace function public.agent_messages_preparar()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_task record;
begin
  -- erro claro (e igual para qualquer projeto sem acesso) antes de qualquer validação
  if current_user in ('anon', 'authenticated') and not public.tem_acesso_projeto(new.project_id, 'editor') then
    raise exception 'agent_messages: sem permissão no projeto.' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' then
    if new.project_id is distinct from old.project_id then
      raise exception 'agent_messages: project_id não pode ser alterado.';
    end if;
    if new.criado_por is distinct from old.criado_por then
      new.criado_por := old.criado_por;
    end if;
    if new.task_id is not distinct from old.task_id and new.resposta_de is not distinct from old.resposta_de then
      return new;
    end if;
  elsif current_user in ('anon', 'authenticated') then
    new.criado_por := public.usuario_atual();       -- a interface não escolhe o autor
  end if;

  new.remetente    := btrim(new.remetente);
  new.destinatario := nullif(btrim(new.destinatario), '');

  if new.task_id is null and new.task_codigo is not null then
    select id into new.task_id from public.tasks
     where project_id = new.project_id and codigo = new.task_codigo;
    if new.task_id is null then
      raise exception 'agent_messages: task % não existe no projeto.', new.task_codigo;
    end if;
  end if;
  if new.task_id is not null then
    select id, project_id, codigo into v_task from public.tasks where id = new.task_id;
    if v_task.project_id is distinct from new.project_id then
      raise exception 'agent_messages: a task % não pertence ao projeto do recado.', new.task_id;
    end if;
    new.task_codigo := v_task.codigo;
  end if;
  if new.resposta_de is not null and not exists (
       select 1 from public.agent_messages where id = new.resposta_de and project_id = new.project_id) then
    raise exception 'agent_messages: o recado respondido (%) não existe no projeto.', new.resposta_de;
  end if;
  return new;
end;
$$;

drop trigger if exists agent_messages_preparar_trg on public.agent_messages;
create trigger agent_messages_preparar_trg
    before insert or update on public.agent_messages
    for each row execute function public.agent_messages_preparar();

drop trigger if exists agent_messages_updated_at_trg on public.agent_messages;
create trigger agent_messages_updated_at_trg
    before update on public.agent_messages
    for each row execute function public.set_updated_at();

-- Caixa de entrada de um agente: recados para ele ou para todos (não arquivados,
-- não escritos por ele). p_marcar_lidos marca como lidos os recados dirigidos a
-- ele (recados para todos não são marcados; use p_desde para paginar).
create or replace function public.ler_recados(
  p_projeto           text,
  p_agente            text,
  p_somente_nao_lidos boolean     default true,
  p_marcar_lidos      boolean     default false,
  p_desde             timestamptz default null,
  p_limite            int         default 50
)
returns setof public.agent_messages
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_pid    bigint := public.projeto_id_por_slug(p_projeto);
  v_agente text   := nullif(btrim(p_agente), '');
begin
  if v_pid is null then
    raise exception 'ler_recados: projeto "%" não encontrado.', p_projeto;
  end if;
  if v_agente is null then
    raise exception 'ler_recados: informe o agente.';
  end if;

  return query
  with caixa as (
    select m.id
      from public.agent_messages m
     where m.project_id = v_pid
       and not m.arquivado
       and m.remetente <> v_agente
       and (m.destinatario is null or m.destinatario = v_agente)
       and (not p_somente_nao_lidos or m.destinatario is null or m.lido_em is null)
       and (p_desde is null or m.created_at > p_desde)
     order by m.created_at, m.id
     limit least(greatest(coalesce(p_limite, 50), 1), 200)
  ), marcados as (
    update public.agent_messages m
       set lido_em = now(), lido_por = v_agente
      from caixa c
     where p_marcar_lidos and m.id = c.id and m.destinatario is not null and m.lido_em is null
    returning m.*
  )
  select x.* from (
    select * from marcados
    union all
    select m.* from public.agent_messages m join caixa c on c.id = m.id
     where m.id not in (select id from marcados)
  ) x
  order by x.created_at, x.id;
end;
$$;

comment on function public.ler_recados(text, text, boolean, boolean, timestamptz, int) is
  'Caixa de entrada de um agente no projeto (recados dirigidos a ele + para todos), com marcação opcional de leitura.';

-- -----------------------------------------------------------------------------
-- project_rules
-- -----------------------------------------------------------------------------
create table if not exists public.project_rules (
    id              bigint      generated by default as identity primary key,
    project_id      bigint      not null references public.projects (id) on delete cascade,
    arquivo         text        not null,                 -- caminho no repositório (ex.: AGENTS.md)
    secao           text        not null default '',      -- título da seção ('' = arquivo inteiro)
    ordem           int         not null default 0,       -- posição da seção no arquivo
    conteudo        text        not null,
    md5             text        generated always as (md5(conteudo)) stored,
    commit_sha      text,                                  -- commit do repositório de onde veio
    sincronizado_em timestamptz,
    ativo           boolean     not null default true,
    criado_por      uuid        default public.usuario_atual(),
    atualizado_por  uuid,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    constraint project_rules_secao_key unique (project_id, arquivo, secao),
    constraint project_rules_arquivo_check
      check (btrim(arquivo) <> '' and length(arquivo) <= 300 and arquivo !~ '(^/|\.\.)'),
    constraint project_rules_secao_check check (length(secao) <= 300),
    constraint project_rules_conteudo_check check (length(conteudo) <= 200000)
);

comment on table public.project_rules is
  'Regras do repositório de cada projeto, por seção, com md5 do conteúdo para conferência com o arquivo.';

create index if not exists project_rules_projeto_idx on public.project_rules (project_id, arquivo, ordem);

create or replace function public.project_rules_preparar()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and new.project_id is distinct from old.project_id then
    raise exception 'project_rules: project_id não pode ser alterado.';
  end if;
  new.arquivo := btrim(new.arquivo);
  new.secao   := btrim(coalesce(new.secao, ''));
  if current_user in ('anon', 'authenticated') then
    if tg_op = 'INSERT' then
      new.criado_por := public.usuario_atual();
    else
      new.criado_por := old.criado_por;
    end if;
    new.atualizado_por := public.usuario_atual();
  end if;
  return new;
end;
$$;

drop trigger if exists project_rules_preparar_trg on public.project_rules;
create trigger project_rules_preparar_trg
    before insert or update on public.project_rules
    for each row execute function public.project_rules_preparar();

drop trigger if exists project_rules_updated_at_trg on public.project_rules;
create trigger project_rules_updated_at_trg
    before update on public.project_rules
    for each row execute function public.set_updated_at();

-- Confere as seções locais (lidas do repositório) contra o banco.
-- p_secoes: [{"arquivo": "AGENTS.md", "secao": "## 1. Regras", "md5": "<md5 do conteúdo>"}, ...]
-- situacao: igual | diverge | so_local | so_banco (regras inativas são ignoradas).
create or replace function public.conferir_regras(p_projeto text, p_secoes jsonb)
returns table (arquivo text, secao text, situacao text, md5_local text, md5_banco text)
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  v_pid bigint := public.projeto_id_por_slug(p_projeto);
begin
  if v_pid is null then
    raise exception 'conferir_regras: projeto "%" não encontrado.', p_projeto;
  end if;
  if p_secoes is null or jsonb_typeof(p_secoes) <> 'array' then
    raise exception 'conferir_regras: p_secoes deve ser um array JSON.';
  end if;

  return query
  with locais as (
    select btrim(e->>'arquivo') as arquivo, btrim(coalesce(e->>'secao', '')) as secao, lower(e->>'md5') as md5
      from jsonb_array_elements(p_secoes) e
  ), banco as (
    select r.arquivo, r.secao, r.md5 from public.project_rules r
     where r.project_id = v_pid and r.ativo
  )
  select coalesce(l.arquivo, b.arquivo), coalesce(l.secao, b.secao),
         case when b.md5 is null then 'so_local'
              when l.md5 is null and l.arquivo is null then 'so_banco'
              when l.md5 = b.md5 then 'igual'
              else 'diverge' end,
         l.md5, b.md5
    from locais l
    full join banco b on b.arquivo = l.arquivo and b.secao = l.secao
   order by 1, 2;
end;
$$;

comment on function public.conferir_regras(text, jsonb) is
  'Compara seções locais (arquivo, secao, md5) com project_rules do projeto: igual, diverge, so_local, so_banco.';

-- -----------------------------------------------------------------------------
-- RLS e permissões
-- -----------------------------------------------------------------------------
alter table public.agent_messages enable row level security;
alter table public.project_rules  enable row level security;

revoke all on public.agent_messages, public.project_rules from anon, authenticated;
grant select, insert                                on public.agent_messages to authenticated;
grant update (lido_em, lido_por, arquivado)         on public.agent_messages to authenticated;  -- sem DELETE
grant select, insert, update, delete                on public.project_rules  to authenticated;
grant all on public.agent_messages, public.project_rules to service_role;
grant usage, select on all sequences in schema public to service_role;

drop policy if exists agent_messages_select on public.agent_messages;
create policy agent_messages_select on public.agent_messages for select to authenticated
  using (public.tem_acesso_projeto(project_id, 'viewer'));

drop policy if exists agent_messages_insert on public.agent_messages;
create policy agent_messages_insert on public.agent_messages for insert to authenticated
  with check (public.tem_acesso_projeto(project_id, 'editor'));

drop policy if exists agent_messages_update on public.agent_messages;
create policy agent_messages_update on public.agent_messages for update to authenticated
  using (public.tem_acesso_projeto(project_id, 'editor'))
  with check (public.tem_acesso_projeto(project_id, 'editor'));

drop policy if exists project_rules_select on public.project_rules;
create policy project_rules_select on public.project_rules for select to authenticated
  using (public.tem_acesso_projeto(project_id, 'viewer'));

drop policy if exists project_rules_insert on public.project_rules;
create policy project_rules_insert on public.project_rules for insert to authenticated
  with check (public.tem_acesso_projeto(project_id, 'owner'));

drop policy if exists project_rules_update on public.project_rules;
create policy project_rules_update on public.project_rules for update to authenticated
  using (public.tem_acesso_projeto(project_id, 'owner'))
  with check (public.tem_acesso_projeto(project_id, 'owner'));

drop policy if exists project_rules_delete on public.project_rules;
create policy project_rules_delete on public.project_rules for delete to authenticated
  using (public.tem_acesso_projeto(project_id, 'owner'));

-- Funções: triggers só internamente; consultas para authenticated (sob RLS) e service_role.
