-- =============================================================================
-- Dashboard AI — 01_tasks_schema.sql
-- Fila de tarefas da IA (`public.tasks`), compartilhada por vários projetos:
-- tabela, restrições, índices e triggers.
--
-- Idempotente: pode ser executado várias vezes (SQL Editor do Supabase ou psql)
-- sem erro e sem perder dados; também atualiza instalações da versão anterior
-- (sem project_id). Depende de 00_projects_roles.sql.
-- Ordem de aplicação: 00 -> 01 -> 02 -> 03 -> 04 -> 05 (ver database/README.md).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Tabela principal da fila de tarefas
-- -----------------------------------------------------------------------------
create table if not exists public.tasks (
    id              bigint generated by default as identity primary key,
    project_id      bigint      not null default public.projeto_padrao_id()
                                references public.projects (id),
    codigo          text        not null,                    -- ex.: TASK-0001 (único por projeto; gerado se vier nulo)
    titulo          text        not null,
    instrucao       text        not null,                    -- instrução completa (Markdown) para a IA
    tipo            text        not null default 'ia',       -- ia = executada por agente | humano = etapa de pessoa (aprovação, teste)
    origem          text        not null default 'ui',       -- de onde a task veio
    prioridade      smallint    not null default 3,          -- 1 = mais alta ... 5 = mais baixa
    ordem           integer     not null default 0,          -- desempate dentro da mesma prioridade
    dependencias    text[]      not null default '{}'::text[], -- códigos (do mesmo projeto) que precisam estar concluídos
    executar        boolean     not null default true,       -- chave ON/OFF: false = fora da fila
    status          text        not null default 'pendente',
    tentativas      integer     not null default 0,
    max_tentativas  integer     not null default 3,
    executar_apos   timestamptz,                             -- só entra na fila a partir deste instante
    resultado       text,                                    -- relatório gravado pela IA ao finalizar
    pr_url          text,                                    -- link do Pull Request
    commit_sha      text,                                    -- SHA do commit entregue
    trava_frente    text,                                    -- agente/rotina que segura a trava
    trava_em        timestamptz,                             -- momento em que a trava foi adquirida (expira em 90 min)
    iniciado_em     timestamptz,
    concluido_em    timestamptz,
    arquivo_md      text,                                    -- caminho do .md espelho no repositório do projeto
    md5_md          text,                                    -- md5 do .md na última sincronização
    sincronizado_em timestamptz,                             -- última conferência banco x repositório
    log_id          bigint,                                  -- última linha de agendamento_tarefa_logs (FK em 02)
    excluido        boolean     not null default false,      -- exclusão lógica
    excluido_em     timestamptz,
    criado_por      uuid        default public.usuario_atual(),
    atualizado_por  uuid        default public.usuario_atual(),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);

