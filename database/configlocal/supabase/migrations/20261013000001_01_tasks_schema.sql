-- -----------------------------------------------------------------------------
-- Trigger 1 (roda primeiro, por ordem alfabética): guarda da interface.
-- Quando a escrita vem de um usuário da API (papéis anon/authenticated), e não
-- das funções da fila (security definer) nem do service_role:
--   * nunca põe nem tira uma task de `em_execucao` (só pegar/finalizar/liberar);
--   * não mexe em trava, tentativas (exceto zerar ao reabrir) nem datas do ciclo;
--   * `concluida` pela interface só para tasks do tipo `humano`;
--   * project_id não muda depois de criada.
-- -----------------------------------------------------------------------------
create or replace function public.tasks_guarda_interface()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and new.project_id is distinct from old.project_id then
    raise exception 'tasks: project_id não pode ser alterado (task %)', old.codigo;
  end if;

  if current_user not in ('anon', 'authenticated') then
    return new;  -- funções da fila, service_role ou conexão direta
  end if;

  if tg_op = 'INSERT' then
    if new.status not in ('pendente', 'cancelada') then
      raise exception 'tasks: uma task nova só pode nascer pendente ou cancelada';
    end if;
    new.tentativas   := 0;
    new.trava_frente := null;
    new.trava_em     := null;
    new.criado_por   := public.usuario_atual();
    new.atualizado_por := public.usuario_atual();
    return new;
  end if;

  if old.status = 'em_execucao' then
    raise exception 'tasks: a task % está em execução e não pode ser alterada pela interface', old.codigo;
  end if;
  if new.status = 'em_execucao' then
    raise exception 'tasks: só a fila (pegar_proxima_task) coloca uma task em execução';
  end if;
  if new.status = 'concluida' and old.status <> 'concluida' and new.tipo <> 'humano' then
    raise exception 'tasks: só tasks do tipo humano são concluídas pela interface (task %)', old.codigo;
  end if;
  if new.trava_frente is distinct from old.trava_frente or new.trava_em is distinct from old.trava_em then
    raise exception 'tasks: a trava só é alterada pelas funções da fila';
  end if;
  if new.tentativas is distinct from old.tentativas and new.tentativas <> 0 then
    raise exception 'tasks: tentativas só podem ser zeradas (ao reabrir) pela interface';
  end if;

  new.iniciado_em    := old.iniciado_em;
  new.criado_por     := old.criado_por;
  new.atualizado_por := public.usuario_atual();
  return new;
end;
$$;

drop trigger if exists tasks_a_guarda_interface_trg on public.tasks;
create trigger tasks_a_guarda_interface_trg
    before insert or update on public.tasks
    for each row execute function public.tasks_guarda_interface();

-- -----------------------------------------------------------------------------
-- Trigger 2: gera o código <PREFIXO>-NNNN por projeto quando não informado.
-- security definer: o contador fica em projects (que a interface não altera).
-- -----------------------------------------------------------------------------
create or replace function public.tasks_gerar_codigo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_prefixo text;
  v_numero  integer;
begin
  if new.codigo is null or btrim(new.codigo) = '' then
    loop
      update public.projects p
         set proximo_numero = p.proximo_numero + 1
       where p.id = new.project_id
      returning p.prefixo_codigo, p.proximo_numero - 1 into v_prefixo, v_numero;
      if v_prefixo is null then
        raise exception 'tasks: projeto % não existe', new.project_id;
      end if;
      new.codigo := v_prefixo || '-' || lpad(v_numero::text, 4, '0');
      -- pula códigos já usados (ex.: importados com código manual)
      exit when not exists (
        select 1 from public.tasks t where t.project_id = new.project_id and t.codigo = new.codigo);
    end loop;
  else
    new.codigo := btrim(new.codigo);
  end if;
  return new;
end;
$$;

drop trigger if exists tasks_gerar_codigo_trg on public.tasks;
create trigger tasks_gerar_codigo_trg
    before insert on public.tasks
    for each row execute function public.tasks_gerar_codigo();

-- Ajusta o contador dos projetos às tasks já existentes (instalações anteriores).
update public.projects p
   set proximo_numero = greatest(p.proximo_numero, x.maior + 1)
  from (
    select t.project_id, max(substring(t.codigo from '-(\d+)$')::int) as maior
      from public.tasks t
     where t.codigo ~ '-\d+$'
     group by t.project_id
  ) x
 where x.project_id = p.id
   and p.proximo_numero <= x.maior;

-- -----------------------------------------------------------------------------
-- Trigger 3: valida dependências (mesmo projeto, existentes, sem a própria task,
-- sem repetição e sem ciclo).
-- -----------------------------------------------------------------------------
create or replace function public.tasks_validar_dependencias()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_faltando text;
begin
  new.dependencias := coalesce(
    (select array_agg(distinct btrim(d) order by btrim(d))
       from unnest(new.dependencias) d where btrim(d) <> ''), '{}');

  if cardinality(new.dependencias) = 0 then
    return new;
  end if;
  if tg_op = 'UPDATE' and new.dependencias = old.dependencias then
    return new;
  end if;

  if new.codigo = any(new.dependencias) then
    raise exception 'tasks: a task % não pode depender dela mesma', new.codigo;
  end if;

  select d into v_faltando
    from unnest(new.dependencias) d
   where not exists (select 1 from public.tasks t where t.project_id = new.project_id and t.codigo = d)
   limit 1;
  if v_faltando is not null then
    raise exception 'tasks: dependência % não existe no projeto da task %', v_faltando, new.codigo;
  end if;

  -- ciclo: alguma dependência (direta ou indireta) depende desta task?
  if exists (
    with recursive cadeia(codigo) as (
      select unnest(new.dependencias)
      union
      select unnest(t.dependencias)
        from public.tasks t
        join cadeia c on c.codigo = t.codigo
       where t.project_id = new.project_id
    )
    select 1 from cadeia where codigo = new.codigo
  ) then
    raise exception 'tasks: dependências de % formam um ciclo', new.codigo;
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_validar_dependencias_trg on public.tasks;
create trigger tasks_validar_dependencias_trg
    before insert or update on public.tasks
    for each row execute function public.tasks_validar_dependencias();

