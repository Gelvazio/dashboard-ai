revoke all on function public.project_rules_preparar()  from public, anon, authenticated;
revoke all on function public.ler_recados(text, text, boolean, boolean, timestamptz, int) from public, anon;
revoke all on function public.conferir_regras(text, jsonb) from public, anon;
grant execute on function public.ler_recados(text, text, boolean, boolean, timestamptz, int) to authenticated, service_role;
grant execute on function public.conferir_regras(text, jsonb) to authenticated, service_role;
