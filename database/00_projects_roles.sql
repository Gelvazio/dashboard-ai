-- =============================================================================
-- Dashboard AI — 00_projects_roles.sql
-- Base multi-projeto e papéis: o Dashboard AI é um gerenciador GENÉRICO de tasks
-- de IA, usado por qualquer projeto. Este arquivo cria:
--   * utilitários: set_updated_at(), usuario_atual(), papel_requisicao()
--   * public.projects (+ projeto `default`) e projeto_padrao_id()
--   * public.user_roles (papel global: admin | member)
--   * public.project_members (papel no projeto: owner | editor | viewer)
--   * eh_administrador() e tem_acesso_projeto() (usadas nas políticas RLS)
--   * migração: professores_administradores -> user_roles (e remoção do legado)
--
-- Idempotente. Ordem de aplicação: 00 -> 01 -> 02 -> 03 -> 04 -> 05.
-- Funciona no Supabase e em PostgreSQL puro (auth.uid()/auth.jwt() opcionais).
-- =============================================================================

create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- Utilitários
-- -----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Claims do JWT da requisição (PostgREST/Supabase). null em conexão direta ao banco.
create or replace function public.jwt_claims()
returns jsonb
language plpgsql
stable
set search_path = public
as $$
begin
  return nullif(current_setting('request.jwt.claims', true), '')::jsonb;
exception when others then
  return null;
end;
$$;

-- Usuário autenticado (auth.users.id) ou null. Equivale a auth.uid() do Supabase.
create or replace function public.usuario_atual()
returns uuid
language plpgsql
stable
set search_path = public
as $$
begin
  return nullif(public.jwt_claims() ->> 'sub', '')::uuid;
exception when others then
  return null;
end;
$$;

-- Papel da requisição: 'anon' | 'authenticated' | 'service_role' | null (conexão direta).
create or replace function public.papel_requisicao()
returns text
language sql
stable
set search_path = public
as $$
  select public.jwt_claims() ->> 'role';
$$;

-- -----------------------------------------------------------------------------
-- Projetos
-- -----------------------------------------------------------------------------
create table if not exists public.projects (
    id              bigint generated by default as identity primary key,
    slug            text        not null unique,          -- identificador curto: 'default', 'meu-app'
    nome            text        not null,
    descricao       text,
    repositorio     text,                                  -- ex.: owner/repo no GitHub
    branch_padrao   text        not null default 'main',
    prefixo_codigo  text        not null default 'TASK',   -- código das tasks: <PREFIXO>-0001
    proximo_numero  integer     not null default 1,        -- contador do código, por projeto
    ativo           boolean     not null default true,     -- false = a fila do projeto não é consumida
    excluido        boolean     not null default false,    -- exclusão lógica
    criado_por      uuid        default public.usuario_atual(),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),

    constraint projects_slug_check   check (slug ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
    constraint projects_prefixo_check check (prefixo_codigo ~ '^[A-Z][A-Z0-9]{0,15}$'),
    constraint projects_numero_check check (proximo_numero >= 1)
);

comment on table  public.projects                is 'Projetos que compartilham a fila de tasks e a memória do Dashboard AI.';
comment on column public.projects.slug           is 'Identificador curto e único (usado por agentes, MCP e scripts).';
comment on column public.projects.prefixo_codigo is 'Prefixo do código das tasks deste projeto (ex.: TASK -> TASK-0001).';
comment on column public.projects.ativo          is 'false = pegar_proxima_task ignora as tasks do projeto.';

drop trigger if exists projects_set_updated_at_trg on public.projects;
create trigger projects_set_updated_at_trg
    before update on public.projects
    for each row execute function public.set_updated_at();

insert into public.projects (slug, nome, descricao)
values ('default', 'Projeto padrão', 'Projeto criado automaticamente; recebe as tasks sem projeto informado.')
on conflict (slug) do nothing;

-- id do projeto `default` (usado como valor padrão de project_id nas tasks)
create or replace function public.projeto_padrao_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.projects where slug = 'default';
$$;

-- id de um projeto pelo slug (null se não existir)
create or replace function public.projeto_id_por_slug(p_slug text)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.projects where slug = lower(btrim(p_slug)) and not excluido;
$$;

-- -----------------------------------------------------------------------------
-- Papéis
-- -----------------------------------------------------------------------------
create table if not exists public.user_roles (
    user_id    uuid        primary key,                    -- auth.users.id
    role       text        not null default 'member',
    email      text,
    nome       text,
    created_at timestamptz not null default now(),
    constraint user_roles_role_check check (role in ('admin', 'member'))
);

comment on table public.user_roles is 'Papel global do usuário: admin (acesso total) ou member (acesso só aos projetos em project_members).';

create table if not exists public.project_members (
    project_id bigint      not null references public.projects (id) on delete cascade,
    user_id    uuid        not null,                       -- auth.users.id
    role       text        not null default 'viewer',
    created_at timestamptz not null default now(),
    primary key (project_id, user_id),
    constraint project_members_role_check check (role in ('owner', 'editor', 'viewer'))
);

create index if not exists project_members_user_idx on public.project_members (user_id);

comment on table public.project_members is 'Papel do usuário em cada projeto: owner > editor > viewer.';

-- true se o usuário (padrão: o da requisição) é administrador global:
-- JWT app_metadata.role = 'admin' (definido só pelo servidor) ou user_roles.role = 'admin'.
create or replace function public.eh_administrador(p_user_id uuid default null)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_uid uuid := coalesce(p_user_id, public.usuario_atual());
begin
  if p_user_id is null and (public.jwt_claims() -> 'app_metadata' ->> 'role') = 'admin' then
    return true;
  end if;
  if v_uid is null then
    return false;
  end if;
  return exists (select 1 from public.user_roles r where r.user_id = v_uid and r.role = 'admin');
end;
$$;

comment on function public.eh_administrador(uuid) is
  'true se o usuário (padrão: o da requisição) é administrador global (JWT app_metadata.role = admin ou user_roles).';

-- true se o usuário da requisição tem no projeto pelo menos o papel p_min_role
-- (viewer < editor < owner). Administrador global sempre tem acesso.
create or replace function public.tem_acesso_projeto(p_project_id bigint, p_min_role text default 'viewer')
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_uid uuid := public.usuario_atual();
  v_min int  := case p_min_role when 'owner' then 3 when 'editor' then 2 else 1 end;
begin
  if public.eh_administrador() then
    return true;
  end if;
  if v_uid is null or p_project_id is null then
    return false;
  end if;
  return exists (
    select 1 from public.project_members m
     where m.project_id = p_project_id
       and m.user_id = v_uid
       and (case m.role when 'owner' then 3 when 'editor' then 2 else 1 end) >= v_min
  );
end;
$$;

comment on function public.tem_acesso_projeto(bigint, text) is
  'true se o usuário da requisição tem papel >= p_min_role (viewer|editor|owner) no projeto, ou é administrador.';

-- -----------------------------------------------------------------------------
-- Migração do legado (versão anterior de 04_rpc_functions.sql):
-- professores_administradores -> user_roles (admin) e remoção da função antiga.
-- -----------------------------------------------------------------------------
do $$
begin
  if to_regclass('public.professores_administradores') is not null then
    insert into public.user_roles (user_id, role, email, nome)
    select pa.user_id, 'admin', pa.email, pa.nome
      from public.professores_administradores pa
    on conflict (user_id) do update set role = 'admin';
    drop table public.professores_administradores;
  end if;
end $$;

