-- =============================================================================
-- Dashboard AI — 07_agent_events.sql  (SUB-35)
-- Eventos dos agentes para o monitor em tempo real: início/fim de etapas,
-- progresso, erros, heartbeats, travas/liberações do quadro e commits, emitidos
-- pelo worker LangGraph, pela ferramenta MCP `agent_event` e pelo espelho do
-- quadro (`scripts/espelhar_quadro_eventos.py`).
--
--   agent_events : um evento por linha, por projeto e, opcionalmente, por task.
--                  chave_idempotencia (única por projeto) evita duplicar o mesmo
--                  evento quando o emissor repete o envio.
--
-- Partes deste arquivo (cada uma é uma subtarefa):
--   SUB-35.1 tabela e índices (este bloco)
--   SUB-35.2 trigger validar_agent_event
--   SUB-35.3 RLS (viewer lê, editor inclui)
--   SUB-35.4 publicação no Supabase Realtime
--   SUB-35.5 função atividade_atual_agentes(p_project_id)
--
-- Idempotente. Depende de 00 a 06 (aplicar depois do 06).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- agent_events (SUB-35.1)
-- -----------------------------------------------------------------------------
create table if not exists public.agent_events (
    id                 bigint      generated by default as identity primary key,
    project_id         bigint      not null references public.projects (id) on delete cascade,
    task_id            bigint      references public.tasks (id) on delete set null,
    task_codigo        text,                                  -- código da task (ex.: SUB-35.1)
    agente             text        not null,                  -- quem emitiu (ex.: DashboardAI-Clone 05)
    execucao_id        text,                                  -- thread/execução do LangGraph
    etapa              text,                                  -- nó do grafo ou passo
    tipo               text        not null,
    status             text,                                  -- status livre informado pelo emissor
    mensagem           text,
    metadados          jsonb       not null default '{}'::jsonb,
    chave_idempotencia text,                                  -- única por projeto (null = sem deduplicação)
    criado_por         uuid        default public.usuario_atual(),
    created_at         timestamptz not null default now(),
    constraint agent_events_tipo_check
      check (tipo in ('inicio', 'progresso', 'fim', 'erro', 'heartbeat', 'trava', 'liberacao', 'commit')),
    constraint agent_events_agente_check check (btrim(agente) <> '' and length(agente) <= 120),
    constraint agent_events_execucao_id_check check (execucao_id is null or length(execucao_id) <= 200),
    constraint agent_events_etapa_check check (etapa is null or length(etapa) <= 120),
    constraint agent_events_mensagem_check check (mensagem is null or length(mensagem) <= 2000),
    constraint agent_events_metadados_check check (jsonb_typeof(metadados) = 'object'),
    constraint agent_events_idempotencia_key unique (project_id, chave_idempotencia)
);

comment on table public.agent_events is
  'Eventos dos agentes (início/fim de etapa, progresso, erro, heartbeat, trava, liberação, commit) por projeto, para o monitor em tempo real (SUB-35). chave_idempotencia é única por projeto.';

create index if not exists agent_events_projeto_recentes_idx
    on public.agent_events (project_id, created_at desc);
create index if not exists agent_events_projeto_agente_idx
    on public.agent_events (project_id, agente, created_at desc);
