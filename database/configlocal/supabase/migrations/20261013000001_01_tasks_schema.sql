-- -----------------------------------------------------------------------------
-- Trigger 5: coerência de ciclo de vida
--   * entrar em `em_execucao` registra iniciado_em;
--   * sair de `em_execucao` libera a trava;
--   * status final (concluida/recusada/erro/cancelada) registra concluido_em;
--   * voltar para `pendente` (reabrir) limpa concluido_em/iniciado_em;
--   * exclusão lógica registra excluido_em e desliga a execução.
-- -----------------------------------------------------------------------------
create or replace function public.tasks_ciclo_de_vida()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'em_execucao' and (tg_op = 'INSERT' or old.status is distinct from 'em_execucao') then
    new.iniciado_em := coalesce(new.iniciado_em, now());
  end if;

  if new.status <> 'em_execucao' then
    new.trava_frente := null;
    new.trava_em     := null;
  end if;

  if new.status in ('concluida', 'recusada', 'erro', 'cancelada') then
    if tg_op = 'INSERT' or old.status is distinct from new.status then
      new.concluido_em := now();
    end if;
  elsif new.status = 'pendente' then
    new.concluido_em := null;
    new.iniciado_em  := null;
  end if;

  if new.excluido and (tg_op = 'INSERT' or not old.excluido) then
    new.excluido_em := coalesce(new.excluido_em, now());
    new.executar    := false;
  elsif not new.excluido then
    new.excluido_em := null;
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_ciclo_de_vida_trg on public.tasks;
create trigger tasks_ciclo_de_vida_trg
    before insert or update on public.tasks
    for each row execute function public.tasks_ciclo_de_vida();
