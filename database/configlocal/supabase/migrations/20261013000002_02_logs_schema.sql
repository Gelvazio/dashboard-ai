-- =============================================================================
-- Dashboard AI — 02_logs_schema.sql
-- Histórico de execuções dos agentes/agendadores (`public.agendamento_tarefa_logs`),
-- por projeto. Uma linha por execução (inclusive "sem_tarefa" quando a fila está vazia).
--
-- Idempotente; atualiza instalações da versão anterior. Depende de 00 e 01.
-- =============================================================================

create table if not exists public.agendamento_tarefa_logs (
    id                 bigint generated by default as identity primary key,
    project_id         bigint      references public.projects (id),
    data_hora          timestamptz not null default now(),   -- momento do registro
    rotina             text        not null,                 -- nome da rotina/agendamento que rodou
    status             text        not null,                 -- concluida | recusada | erro | sem_tarefa
    task_id            bigint      references public.tasks (id) on delete set null,
    task_codigo        text,                                  -- cópia do código para histórico
    agente             text,                                  -- agente que executou (texto livre: Claude, Gemini, Grok...)
    detalhes           text,                                  -- mensagem ou relatório resumido
    erro_mensagem      text,
    status_anterior    text,                                  -- status da task antes da execução
    status_novo        text,                                  -- status da task depois da execução
    instrucao_recebida text,                                  -- texto da instrução que o agente recebeu
    repositorio        text,                                  -- ex.: owner/repo
    branch             text,
    commit_sha         text,
    pr_url             text,
    sessao_url         text,                                  -- link da sessão/execução do agente
    arquivos_alterados integer,
    inicio_em          timestamptz,
    fim_em             timestamptz,
    duracao_ms         integer,                               -- tempo de execução em milissegundos
    created_at         timestamptz not null default now()
);

-- Atualização de instalações anteriores ---------------------------------------
alter table public.agendamento_tarefa_logs add column if not exists project_id         bigint;
alter table public.agendamento_tarefa_logs add column if not exists erro_mensagem      text;
alter table public.agendamento_tarefa_logs add column if not exists status_anterior    text;
alter table public.agendamento_tarefa_logs add column if not exists status_novo        text;
alter table public.agendamento_tarefa_logs add column if not exists instrucao_recebida text;
alter table public.agendamento_tarefa_logs add column if not exists repositorio        text;
alter table public.agendamento_tarefa_logs add column if not exists branch             text;
alter table public.agendamento_tarefa_logs add column if not exists commit_sha         text;
alter table public.agendamento_tarefa_logs add column if not exists pr_url             text;
alter table public.agendamento_tarefa_logs add column if not exists sessao_url         text;
alter table public.agendamento_tarefa_logs add column if not exists arquivos_alterados integer;
alter table public.agendamento_tarefa_logs add column if not exists inicio_em          timestamptz;
alter table public.agendamento_tarefa_logs add column if not exists fim_em             timestamptz;

update public.agendamento_tarefa_logs l
   set project_id = coalesce((select t.project_id from public.tasks t where t.id = l.task_id),
                             public.projeto_padrao_id())
 where l.project_id is null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'agendamento_tarefa_logs_project_id_fkey') then
    alter table public.agendamento_tarefa_logs add constraint agendamento_tarefa_logs_project_id_fkey
      foreign key (project_id) references public.projects (id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'agendamento_tarefa_logs_status_check') then
    alter table public.agendamento_tarefa_logs add constraint agendamento_tarefa_logs_status_check
      check (status in ('concluida', 'recusada', 'erro', 'sem_tarefa'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'agendamento_tarefa_logs_duracao_check') then
    alter table public.agendamento_tarefa_logs add constraint agendamento_tarefa_logs_duracao_check
      check (duracao_ms is null or duracao_ms >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'agendamento_tarefa_logs_arquivos_check') then
    alter table public.agendamento_tarefa_logs add constraint agendamento_tarefa_logs_arquivos_check
      check (arquivos_alterados is null or arquivos_alterados >= 0);
  end if;
  -- tasks.log_id -> última execução registrada da task
  if not exists (select 1 from pg_constraint where conname = 'tasks_log_id_fkey') then
    alter table public.tasks add constraint tasks_log_id_fkey
      foreign key (log_id) references public.agendamento_tarefa_logs (id) on delete set null;
  end if;
end $$;

comment on table  public.agendamento_tarefa_logs        is 'Linha do tempo de execuções dos agentes de IA, por projeto (Dashboard AI).';
comment on column public.agendamento_tarefa_logs.status is 'concluida | recusada | erro | sem_tarefa';
comment on column public.agendamento_tarefa_logs.task_codigo is 'Código da task processada (desnormalizado para auditoria).';
comment on column public.agendamento_tarefa_logs.agente is 'Identificação livre do agente/frente (sem e-mail ou dado pessoal).';

-- Índices ---------------------------------------------------------------------
create index if not exists agendamento_tarefa_logs_data_hora_idx
    on public.agendamento_tarefa_logs (data_hora desc);
create index if not exists agendamento_tarefa_logs_status_idx
    on public.agendamento_tarefa_logs (status, data_hora desc);
create index if not exists agendamento_tarefa_logs_task_id_idx
    on public.agendamento_tarefa_logs (task_id);
create index if not exists agendamento_tarefa_logs_projeto_idx
    on public.agendamento_tarefa_logs (project_id, data_hora desc);

-- Preenche task_codigo e project_id a partir de task_id (ou o projeto padrão) ---
create or replace function public.agendamento_logs_preencher_codigo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.task_id is not null then
    select coalesce(new.task_codigo, t.codigo), coalesce(new.project_id, t.project_id)
      into new.task_codigo, new.project_id
      from public.tasks t where t.id = new.task_id;
  end if;
  new.project_id := coalesce(new.project_id, public.projeto_padrao_id());
  return new;
end;
$$;

drop trigger if exists agendamento_logs_preencher_codigo_trg on public.agendamento_tarefa_logs;
create trigger agendamento_logs_preencher_codigo_trg
    before insert on public.agendamento_tarefa_logs
    for each row execute function public.agendamento_logs_preencher_codigo();
