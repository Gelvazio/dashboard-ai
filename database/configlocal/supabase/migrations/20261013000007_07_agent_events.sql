-- =============================================================================
-- Dashboard AI — 07_agent_events.sql  (SUB-35)
-- Eventos dos agentes para o monitor em tempo real: início/fim de etapas,
-- progresso, erros, heartbeats, travas/liberações do quadro e commits, emitidos
-- pelo worker LangGraph, pela ferramenta MCP `agent_event` e pelo espelho do
-- quadro (`scripts/espelhar_quadro_eventos.py`).
--
--   agent_events : um evento por linha, por projeto e, opcionalmente, por task.
--                  chave_idempotencia (única por projeto) evita duplicar o mesmo
--                  evento quando o emissor repete o envio.
--
-- Partes deste arquivo (cada uma é uma subtarefa):
--   SUB-35.1 tabela e índices (este bloco)
--   SUB-35.2 trigger validar_agent_event
--   SUB-35.3 RLS (viewer lê, editor inclui)
--   SUB-35.4 publicação no Supabase Realtime
--   SUB-35.5 função atividade_atual_agentes(p_project_id)
--
-- Idempotente. Depende de 00 a 06 (aplicar depois do 06).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- agent_events (SUB-35.1)
-- -----------------------------------------------------------------------------
create table if not exists public.agent_events (
    id                 bigint      generated by default as identity primary key,
    project_id         bigint      not null references public.projects (id) on delete cascade,
    task_id            bigint      references public.tasks (id) on delete set null,
    task_codigo        text,                                  -- código da task (ex.: SUB-35.1)
    agente             text        not null,                  -- quem emitiu (ex.: DashboardAI-Clone 05)
    execucao_id        text,                                  -- thread/execução do LangGraph
    etapa              text,                                  -- nó do grafo ou passo
    tipo               text        not null,
    status             text,                                  -- status livre informado pelo emissor
    mensagem           text,
    metadados          jsonb       not null default '{}'::jsonb,
    chave_idempotencia text,                                  -- única por projeto (null = sem deduplicação)
    criado_por         uuid        default public.usuario_atual(),
    created_at         timestamptz not null default now(),
    constraint agent_events_tipo_check
      check (tipo in ('inicio', 'progresso', 'fim', 'erro', 'heartbeat', 'trava', 'liberacao', 'commit')),
    constraint agent_events_agente_check check (btrim(agente) <> '' and length(agente) <= 120),
    constraint agent_events_execucao_id_check check (execucao_id is null or length(execucao_id) <= 200),
    constraint agent_events_etapa_check check (etapa is null or length(etapa) <= 120),
    constraint agent_events_mensagem_check check (mensagem is null or length(mensagem) <= 2000),
    constraint agent_events_metadados_check check (jsonb_typeof(metadados) = 'object'),
    constraint agent_events_idempotencia_key unique (project_id, chave_idempotencia)
);

comment on table public.agent_events is
  'Eventos dos agentes (início/fim de etapa, progresso, erro, heartbeat, trava, liberação, commit) por projeto, para o monitor em tempo real (SUB-35). chave_idempotencia é única por projeto.';

create index if not exists agent_events_projeto_recentes_idx
    on public.agent_events (project_id, created_at desc);
create index if not exists agent_events_projeto_agente_idx
    on public.agent_events (project_id, agente, created_at desc);

-- -----------------------------------------------------------------------------
-- Validação (SUB-35.2): task do mesmo projeto, task_codigo preenchido a partir da
-- task e eventos só-inclusão (update não muda project_id/agente/created_at).
-- security invoker de propósito, como em agent_messages_preparar (06): current_user
-- identifica a interface e a busca da task respeita a RLS.
-- -----------------------------------------------------------------------------
create or replace function public.validar_agent_event()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_task record;
begin
  if tg_op = 'UPDATE' then
    if new.project_id is distinct from old.project_id then
      raise exception 'agent_events: project_id não pode ser alterado (eventos são só-inclusão).';
    end if;
    if new.agente is distinct from old.agente then
      raise exception 'agent_events: agente não pode ser alterado (eventos são só-inclusão).';
    end if;
    if new.created_at is distinct from old.created_at then
      raise exception 'agent_events: created_at não pode ser alterado (eventos são só-inclusão).';
    end if;
    if new.criado_por is distinct from old.criado_por then
      new.criado_por := old.criado_por;
    end if;
  elsif current_user in ('anon', 'authenticated') then
    new.criado_por := public.usuario_atual();       -- a interface não escolhe o autor
  end if;

  new.agente := btrim(new.agente);

  if new.task_id is null and new.task_codigo is not null and tg_op = 'INSERT' then
    select id into new.task_id from public.tasks
     where project_id = new.project_id and codigo = new.task_codigo;
    -- código sem task correspondente é aceito (ex.: subtarefa só no quadro Markdown)
  end if;
  if new.task_id is not null then
    select id, project_id, codigo into v_task from public.tasks where id = new.task_id;
    if not found or v_task.project_id is distinct from new.project_id then
      raise exception 'agent_events: a task % não pertence ao projeto do evento.', new.task_id;
    end if;
    new.task_codigo := v_task.codigo;
  end if;
  return new;
end;
$$;

drop trigger if exists validar_agent_event_trg on public.agent_events;
create trigger validar_agent_event_trg
    before insert or update on public.agent_events
    for each row execute function public.validar_agent_event();

-- -----------------------------------------------------------------------------
-- RLS e permissões (SUB-35.3): viewer lê, editor inclui; sem UPDATE/DELETE pela
-- interface (eventos são só-inclusão; só service_role/administração apaga).
-- -----------------------------------------------------------------------------
alter table public.agent_events enable row level security;

revoke all on public.agent_events from anon, authenticated;
grant select, insert on public.agent_events to authenticated;
grant all on public.agent_events to service_role;

drop policy if exists agent_events_select on public.agent_events;
create policy agent_events_select on public.agent_events for select to authenticated
  using (public.tem_acesso_projeto(project_id, 'viewer'));

drop policy if exists agent_events_insert on public.agent_events;
create policy agent_events_insert on public.agent_events for insert to authenticated
  with check (public.tem_acesso_projeto(project_id, 'editor'));

-- -----------------------------------------------------------------------------
-- Supabase Realtime (SUB-35.4): publica agent_events para o monitor receber
-- inserções ao vivo. Só age se a publicação supabase_realtime existir (no
-- Postgres local de testes ela não existe) e a tabela ainda não estiver nela,
-- então reaplicar o arquivo não falha.
-- -----------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'agent_events'
     ) then
    alter publication supabase_realtime add table public.agent_events;
  end if;
end;
$$;

-- -----------------------------------------------------------------------------
-- atividade_atual_agentes (SUB-35.5): último evento de cada agente do projeto,
-- com o horário do último heartbeat. security invoker: a RLS de agent_events
-- decide o que o usuário vê. Só leitura; não altera travas.
-- -----------------------------------------------------------------------------
drop function if exists public.atividade_atual_agentes(bigint);
create function public.atividade_atual_agentes(p_project_id bigint)
returns table (
  agente              text,
  task_codigo         text,
  etapa               text,
  tipo                text,
  status              text,
  mensagem            text,
  execucao_id         text,
  ultimo_em           timestamptz,
  ultimo_heartbeat_em timestamptz
)
language sql
stable
security invoker
set search_path = public
as $$
  select distinct on (e.agente)
         e.agente, e.task_codigo, e.etapa, e.tipo, e.status, e.mensagem, e.execucao_id,
         e.created_at as ultimo_em,
         (select max(h.created_at) from public.agent_events h
           where h.project_id = e.project_id and h.agente = e.agente and h.tipo = 'heartbeat') as ultimo_heartbeat_em
    from public.agent_events e
   where e.project_id = p_project_id
   order by e.agente, e.created_at desc, e.id desc;
$$;

comment on function public.atividade_atual_agentes(bigint) is
  'Último evento de cada agente do projeto (+ último heartbeat), para o monitor em tempo real (SUB-35). security invoker: respeita a RLS de agent_events.';

revoke all on function public.atividade_atual_agentes(bigint) from public, anon;
grant execute on function public.atividade_atual_agentes(bigint) to authenticated, service_role;
