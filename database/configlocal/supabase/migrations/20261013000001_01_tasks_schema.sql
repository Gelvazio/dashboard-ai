-- Restrições (criadas só se faltarem) ----------------------------------------
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'tasks_project_id_fkey') then
    alter table public.tasks add constraint tasks_project_id_fkey
      foreign key (project_id) references public.projects (id);
  end if;

  -- código único POR PROJETO (a versão anterior tinha unique global em `codigo`)
  if exists (select 1 from pg_constraint where conname = 'tasks_codigo_key') then
    alter table public.tasks drop constraint tasks_codigo_key;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_projeto_codigo_key') then
    alter table public.tasks add constraint tasks_projeto_codigo_key unique (project_id, codigo);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'tasks_status_check') then
    alter table public.tasks add constraint tasks_status_check
      check (status in ('pendente', 'em_execucao', 'concluida', 'recusada', 'erro', 'cancelada'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_tipo_check') then
    alter table public.tasks add constraint tasks_tipo_check check (tipo in ('ia', 'humano'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_origem_check') then
    alter table public.tasks add constraint tasks_origem_check
      check (origem in ('ui', 'repositorio', 'mcp', 'api', 'script'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_prioridade_check') then
    alter table public.tasks add constraint tasks_prioridade_check check (prioridade between 1 and 5);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_tentativas_check') then
    alter table public.tasks add constraint tasks_tentativas_check check (tentativas >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_max_tentativas_check') then
    alter table public.tasks add constraint tasks_max_tentativas_check check (max_tentativas between 1 and 20);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'tasks_trava_consistente_check') then
    alter table public.tasks add constraint tasks_trava_consistente_check
      check ((trava_frente is null) = (trava_em is null));
  end if;
end $$;

