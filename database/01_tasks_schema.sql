-- Dashboard AI — 01_tasks_schema.sql
-- Fila de tarefas da IA (`public.tasks`): tabela, restrições, índices e triggers.
--
-- Idempotente: pode ser executado várias vezes no SQL Editor do Supabase
-- (ou via psql) sem erro e sem perder dados.
-- Ordem de aplicação: 01 -> 02 -> 03 -> 04 (ver database/README.md).
-- =============================================================================

-- gen_random_uuid() / utilitários (já habilitado no Supabase; garantido aqui)
create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- Função utilitária compartilhada: mantém `updated_at` sempre atualizado.
-- -----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- -----------------------------------------------------------------------------
-- Sequência usada para gerar o código legível da task (TASK-0001, TASK-0002...)
-- -----------------------------------------------------------------------------
create sequence if not exists public.tasks_codigo_seq;

-- -----------------------------------------------------------------------------
-- Tabela principal da fila de tarefas
-- -----------------------------------------------------------------------------
create table if not exists public.tasks (
    id              bigint generated by default as identity primary key,
    codigo          text        not null unique,             -- ex.: TASK-0001 (gerado por trigger se vier nulo)
    titulo          text        not null,
    instrucao       text        not null,                    -- instrução completa (Markdown) para a IA
    prioridade      smallint    not null default 3,          -- 1 = mais alta ... 5 = mais baixa
    ordem           integer     not null default 0,          -- desempate dentro da mesma prioridade
    dependencias    text[]      not null default '{}'::text[], -- códigos de tasks que precisam estar concluídas
    executar        boolean     not null default true,       -- chave ON/OFF: false = fora da fila
    status          text        not null default 'pendente',
    tentativas      integer     not null default 0,
    max_tentativas  integer     not null default 3,
    executar_apos   timestamptz,                             -- só entra na fila a partir deste instante
    resultado       text,                                    -- relatório gravado pela IA ao finalizar
    pr_url          text,                                    -- link do Pull Request no GitHub
    commit_sha      text,                                    -- SHA do commit entregue
    trava_frente    text,                                    -- identificação do agente/rotina que segura a trava
    trava_em        timestamptz,                             -- momento em que a trava foi adquirida (expira em 90 min)
    iniciado_em     timestamptz,
    concluido_em    timestamptz,
    excluido        boolean     not null default false,      -- exclusão lógica
    excluido_em     timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),

    constraint tasks_status_check
        check (status in ('pendente', 'em_execucao', 'concluida', 'recusada', 'erro', 'cancelada')),
    constraint tasks_prioridade_check
        check (prioridade between 1 and 5),
    constraint tasks_tentativas_check
        check (tentativas >= 0),
    constraint tasks_max_tentativas_check
        check (max_tentativas >= 1),
    constraint tasks_trava_consistente_check
        check ((trava_frente is null) = (trava_em is null))
);

comment on table  public.tasks              is 'Fila de tarefas executadas pelos agentes de IA (Dashboard AI).';
comment on column public.tasks.codigo       is 'Código legível e único (TASK-0001). Gerado automaticamente quando omitido.';
comment on column public.tasks.prioridade   is '1 (mais alta) a 5 (mais baixa).';
comment on column public.tasks.executar     is 'Chave ON/OFF. Somente tasks com executar = true são pegas pela fila.';
comment on column public.tasks.status       is 'pendente | em_execucao | concluida | recusada | erro | cancelada';
comment on column public.tasks.trava_frente is 'Agente/rotina que detém o lock da task (lock expira após 90 minutos).';
comment on column public.tasks.trava_em     is 'Instante de aquisição do lock.';
comment on column public.tasks.excluido     is 'Exclusão lógica: a linha permanece para auditoria.';

-- -----------------------------------------------------------------------------
-- Índices
-- -----------------------------------------------------------------------------
-- Ordem de consumo da fila: prioridade -> ordem -> criação
create index if not exists tasks_fila_idx
    on public.tasks (prioridade, ordem, created_at)
    where status = 'pendente' and executar and not excluido;

create index if not exists tasks_status_idx       on public.tasks (status) where not excluido;
create index if not exists tasks_trava_em_idx     on public.tasks (trava_em) where trava_em is not null;
create index if not exists tasks_dependencias_idx on public.tasks using gin (dependencias);

-- -----------------------------------------------------------------------------
-- Trigger: gera o código TASK-NNNN quando não informado
-- -----------------------------------------------------------------------------
create or replace function public.tasks_gerar_codigo()
returns trigger
language plpgsql
as $$
begin
  if new.codigo is null or btrim(new.codigo) = '' then
    new.codigo := 'TASK-' || lpad(nextval('public.tasks_codigo_seq')::text, 4, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists tasks_gerar_codigo_trg on public.tasks;
create trigger tasks_gerar_codigo_trg
    before insert on public.tasks
    for each row execute function public.tasks_gerar_codigo();

-- -----------------------------------------------------------------------------
-- Trigger: updated_at
-- -----------------------------------------------------------------------------
drop trigger if exists tasks_set_updated_at_trg on public.tasks;
create trigger tasks_set_updated_at_trg
    before update on public.tasks
    for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------------------
-- Trigger: coerência de ciclo de vida
--   * entrar em `em_execucao` registra iniciado_em;
--   * sair de `em_execucao` libera a trava;
--   * status final (concluida/recusada/erro/cancelada) registra concluido_em;
--   * voltar para `pendente` (reabrir) limpa concluido_em;
--   * exclusão lógica registra excluido_em e desliga a execução.
-- -----------------------------------------------------------------------------
create or replace function public.tasks_ciclo_de_vida()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'em_execucao' and (tg_op = 'INSERT' or old.status is distinct from 'em_execucao') then
    new.iniciado_em := coalesce(new.iniciado_em, now());
  end if;

  if new.status <> 'em_execucao' then
    new.trava_frente := null;
    new.trava_em     := null;
  end if;

  if new.status in ('concluida', 'recusada', 'erro', 'cancelada') then
    if tg_op = 'INSERT' or old.status is distinct from new.status then
      new.concluido_em := now();
    end if;
  elsif new.status = 'pendente' then
    new.concluido_em := null;
    new.iniciado_em  := null;
  end if;

  if new.excluido and (tg_op = 'INSERT' or not old.excluido) then
    new.excluido_em := coalesce(new.excluido_em, now());
    new.executar    := false;
  elsif not new.excluido then
    new.excluido_em := null;
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_ciclo_de_vida_trg on public.tasks;
create trigger tasks_ciclo_de_vida_trg
    before insert or update on public.tasks
    for each row execute function public.tasks_ciclo_de_vida();
